import assert from 'node:assert/strict';
import { mkdtemp, rm, writeFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import test from 'node:test';

import { closeConnection, initializeDatabase, sessionsDb } from '@/modules/database/index.js';
import { ClaudeSessionsProvider } from '@/modules/providers/list/claude/claude-sessions.provider.js';

const SESSION_ID = 'claude-local-commands';
const CAVEAT = '<local-command-caveat>Caveat: The messages below were generated by the user while running local commands. DO NOT respond to these messages or otherwise consider them in your response unless the user explicitly asks you to.</local-command-caveat>';
const SUMMARY = 'This session is being continued from a previous conversation that ran out of context. The summary below covers the earlier portion of the conversation.\n\nSummary:\n1. The user asked for OK.';

const commandRow = (name: string, args = '') =>
  `<command-name>/${name}</command-name>\n            <command-message>${name}</command-message>\n            <command-args>${args}</command-args>`;

let clock = 0;
function row(uuid: string, fields: Record<string, unknown>) {
  clock += 1;
  return {
    uuid, sessionId: SESSION_ID, isSidechain: false,
    timestamp: new Date(Date.UTC(2026, 9, 20, 17, 14, clock)).toISOString(),
    ...fields,
  };
}
const user = (uuid: string, content: string, fields: Record<string, unknown> = {}) =>
  row(uuid, { type: 'user', message: { role: 'user', content }, ...fields });
const localCommand = (uuid: string, content: string) =>
  row(uuid, { type: 'system', subtype: 'local_command', content, level: 'info', isMeta: false });
const synthetic = (uuid: string, text: string) => row(uuid, {
  type: 'assistant',
  message: { role: 'assistant', model: '<synthetic>', content: [{ type: 'text', text }], usage: { input_tokens: 0, output_tokens: 0 } },
});

/** Rows the bundled CLI wrote for a short session of local commands (trimmed). */
const TRANSCRIPT = [
  user('u1', 'Reply with exactly: OK'),
  row('a1', {
    type: 'assistant',
    message: { role: 'assistant', model: 'claude-opus-5.5', content: [{ type: 'text', text: 'OK' }], usage: { input_tokens: 1602, output_tokens: 4 } },
  }),
  user('caveat1', CAVEAT, { isMeta: true }),
  user('cmd-context', commandRow('context')),
  localCommand('ctx-out', '<local-command-stdout>## Context Usage\n\n**Tokens:** 30.4k / 633k (5%)\n</local-command-stdout>'),
  // Written on the next resume so the conversation alternates again.
  synthetic('placeholder1', 'No response requested.'),
  user('caveat2', CAVEAT, { isMeta: true }),
  user('cmd-compact', commandRow('compact')),
  // The summary is written a moment before its boundary.
  user('summary', SUMMARY, { isCompactSummary: true, isVisibleInTranscriptOnly: true }),
  row('boundary', {
    type: 'system', subtype: 'compact_boundary', content: 'Conversation compacted', level: 'info', parentUuid: null,
    compactMetadata: { trigger: 'manual', preTokens: 30689 },
  }),
  user('compacted', '<local-command-stdout>Compacted </local-command-stdout>'),
  // A command the CLI cannot run headless is echoed as plain text.
  localCommand('model-echo', '/model'),
  localCommand('model-out', '<local-command-stdout>/model isn\'t available in this environment.</local-command-stdout>'),
  user('cmd-compact-again', commandRow('compact', 'keep the API notes')),
  localCommand('compact-err', '<local-command-stderr>Error: No messages to compact</local-command-stderr>'),
];

async function readHistory() {
  const tempRoot = await mkdtemp(path.join(os.tmpdir(), 'claude-local-commands-'));
  const previousDatabasePath = process.env.DATABASE_PATH;
  closeConnection();
  process.env.DATABASE_PATH = path.join(tempRoot, 'auth.db');
  await initializeDatabase();
  try {
    const transcriptPath = path.join(tempRoot, `${SESSION_ID}.jsonl`);
    await writeFile(transcriptPath, `${TRANSCRIPT.map((entry) => JSON.stringify(entry)).join('\n')}\n`, 'utf8');
    const now = new Date().toISOString();
    sessionsDb.createSession(SESSION_ID, 'claude', tempRoot, 'Local commands', now, now, transcriptPath);
    return await new ClaudeSessionsProvider().fetchHistory(SESSION_ID, { providerSessionId: SESSION_ID });
  } finally {
    closeConnection();
    if (previousDatabasePath === undefined) delete process.env.DATABASE_PATH;
    else process.env.DATABASE_PATH = previousDatabasePath;
    await rm(tempRoot, { recursive: true, force: true });
  }
}

test('history shows local commands and their output, and nothing the CLI wrote for itself', { concurrency: false }, async () => {
  const history = await readHistory();

  assert.deepEqual(history.messages.map((message) => `${message.role}:${message.content}`), [
    'user:Reply with exactly: OK',
    'assistant:OK',
    'user:/context',
    'assistant:## Context Usage\n\n**Tokens:** 30.4k / 633k (5%)',
    'user:/compact',
    `assistant:${SUMMARY}`,
    'assistant:Compacted',
    'user:/model',
    'assistant:/model isn\'t available in this environment.',
    'user:/compact keep the API notes',
    'assistant:Error: No messages to compact',
  ]);
  const byContent = new Map(history.messages.map((message) => [message.content, message]));
  // Same id the live reply for this output gets, so the two reconcile.
  assert.equal(byContent.get('## Context Usage\n\n**Tokens:** 30.4k / 633k (5%)')?.id, 'ctx-out_0');
  assert.equal(byContent.get(SUMMARY)?.isCompactSummary, true);
  assert.equal(byContent.get('/model')?.isLocalCommand, true);
  assert.equal(byContent.get('/model')?.commandName, '/model');
  assert.equal(byContent.get('Error: No messages to compact')?.isLocalCommandStdout, true);
});

test('the live stream renders local commands and compaction the way history does', () => {
  const sessions = new ClaudeSessionsProvider();

  // Live, local command output is a `<synthetic>` reply carrying the uuid of
  // the transcript row history reads it from.
  const [output] = sessions.normalizeMessage({
    type: 'assistant', uuid: 'ctx-out', session_id: SESSION_ID, parent_tool_use_id: null,
    message: { role: 'assistant', model: '<synthetic>', content: [{ type: 'text', text: '## Context Usage' }] },
  }, SESSION_ID);
  assert.equal(output.id, 'ctx-out_0');
  assert.equal(output.role, 'assistant');

  // The summary streams as a synthetic user message without the history flag.
  const [summary, ...rest] = sessions.normalizeMessage({
    type: 'user', uuid: 'summary', session_id: SESSION_ID, parent_tool_use_id: null, isSynthetic: true,
    message: { role: 'user', content: SUMMARY },
  }, SESSION_ID);
  assert.equal(rest.length, 0);
  assert.equal(summary.role, 'assistant');
  assert.equal(summary.isCompactSummary, true);
  assert.equal(summary.id, 'summary');

  for (const event of [
    { type: 'system', subtype: 'compact_boundary', uuid: 'boundary', compact_metadata: { trigger: 'auto', pre_tokens: 600_000 } },
    { type: 'system', subtype: 'status', uuid: 'status', status: 'compacting' },
  ]) {
    assert.deepEqual(sessions.normalizeMessage(event, SESSION_ID), [], event.subtype);
  }

  // A user who types the summary's opening words still sends a prompt.
  const [typed] = sessions.normalizeMessage({
    type: 'user', uuid: 'typed', message: { role: 'user', content: SUMMARY },
  }, SESSION_ID);
  assert.equal(typed.role, 'user');
});
